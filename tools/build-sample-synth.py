#!/usr/bin/env python3
"""Developer-only SynthDef generation using installed sclang, not an SC rebuild."""
import os
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
plugin = root / "spikes/vst3-callback"
with tempfile.TemporaryDirectory() as directory:
    directory = Path(directory)
    code = plugin.joinpath("sample_synth.scd").read_text().strip()
    code += '.writeDefFile(' + repr(str(directory)).replace("'", '"') + ');\n0.exit;\n'
    script = directory / "generate.scd"
    script.write_text(code)
    env = dict(os.environ, QT_QPA_PLATFORM="minimal", QT_QUICK_BACKEND="software",
               QT_OPENGL="software", QTWEBENGINE_DISABLE_SANDBOX="1",
               QTWEBENGINE_CHROMIUM_FLAGS="--no-sandbox --disable-gpu")
    run = subprocess.run(["sclang"], input=f'thisProcess.interpreter.executeFile("{script}"); 0.exit;\n',
                         text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         timeout=60, env=env)
    binary = directory / "DexterSample.scsyndef"
    if run.returncode or not binary.exists():
        raise SystemExit(run.stdout[-6000:])
    data = binary.read_bytes()
    lines = [", ".join(f"0x{byte:02x}" for byte in data[i:i+16]) for i in range(0, len(data), 16)]
    plugin.joinpath("sample_synthdef.h").write_text(
        "// Generated by tools/build-sample-synth.py from sample_synth.scd.\n"
        "#pragma once\nstatic constexpr unsigned char kSampleSynthDef[] = {\n    " +
        ",\n    ".join(lines) + "\n};\n")
    print(f"Generated DexterSample: {len(data)} bytes")
