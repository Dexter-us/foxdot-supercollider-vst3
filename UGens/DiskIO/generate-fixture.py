#!/usr/bin/env python3
"""Generate an original CC0 eight-second drum loop; no sample downloads."""
import math
from pathlib import Path
import random
import struct
import sys
import wave

RATE = 48000
root = Path(sys.argv[1])
root.mkdir(parents=True, exist_ok=True)
rng = random.Random(120106)
samples = [0.0] * (RATE * 8)
for step in range(32):
    offset = int(step * .25 * RATE)
    for i in range(int(.22 * RATE)):
        t = i / RATE
        value = 0.0
        if step % 4 == 0:
            # Phase-integrated dropping kick; cosine fade avoids an abrupt tail.
            phase = 2 * math.pi * (48 * t + 105 * .025 * (1 - math.exp(-t / .025)))
            value += .55 * math.sin(phase) * math.exp(-t / .055)
        if step % 4 == 2:
            value += .25 * rng.uniform(-1, 1) * math.exp(-t / .035)
            value += .15 * math.sin(2 * math.pi * 180 * t) * math.exp(-t / .04)
        value += .065 * rng.uniform(-1, 1) * math.exp(-t / .009)
        fade = min(1.0, i / 48) * min(1.0, (int(.22 * RATE) - 1 - i) / 96)
        if offset + i < len(samples):
            samples[offset + i] += value * max(0.0, fade)
with wave.open(str(root / "drum-loop.wav"), "wb") as output:
    output.setparams((2, 2, RATE, len(samples), "NONE", "not compressed"))
    output.writeframes(b"".join(
        struct.pack("<hh", round(max(-1, min(1, value)) * 32767),
                    round(max(-1, min(1, value)) * 32767))
        for value in samples))
(root / "LICENSE.txt").write_text(
    "The drum-loop.wav fixture generated by Dexter U.S. is dedicated to the "
    "public domain under CC0 1.0: https://creativecommons.org/publicdomain/zero/1.0/\n",
    encoding="utf-8")
print("Generated original CC0 stereo drum-loop.wav (48 kHz, 8 seconds)")
